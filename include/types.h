/*
 * Common type definitions used throughout the kernel
 */

#ifndef TYPES_H
#define TYPES_H

/* Basic integer types */
typedef unsigned char u8;      /* 8-bit unsigned integer  */
typedef unsigned short u16;    /* 16-bit unsigned integer */
typedef unsigned int u32;      /* 32-bit unsigned integer */
typedef unsigned long u64;     /* 64-bit unsigned integer */

typedef signed char s8;        /* 8-bit signed integer    */
typedef signed short s16;      /* 16-bit signed integer   */
typedef signed int s32;        /* 32-bit signed integer   */
typedef signed long s64;       /* 64-bit signed integer   */

#endif /* TYPES_H */
